@celery.task(name = "task.send_daily_reminders")
def send_daily_reminder():
    today = date.today()
    horizon = today +timedelta(days=3)

    upcoming = (
        PlacementDrive.query.filter(
            PlacementDrive.status == "approved",
            PlacementDrive.application_deadline != None ,
            PlacementDrive.application_deadline >= today,
            PlacementDrive.application_deadline <=horizon
        ).all()
    )
    if not upcoming:
        return "No Upcoming daedlines in the next 3 days"
    students = StudentProfile.query.join(User).filter(
        User.is_active == True , User.is_blacklisted == False
    ).all()
    sent = 0
    for student in students:
        applied_drive_ids = {a.drive_id for a in student.applications}
        pending = [d for d in upcoming if d.id not in applied_drive_ids]
        if not pending:
            continue
        lines = "".join(
            f"<li><b>{d.job_title}</b> at {d.company.company_name}"
            f"(deadline :{d.application_deadline}) </li>"
            for d in pending
        )
        html = (
            f"<p>Hi {student.name},</p>"
            f"<p>These Placement drives close soon . Apply before the deadline:</P>"
            f"<ul>{lines}</ul>"
            f"<p> - Placement Cell</p>"
        )
        _send_email(student.user.email , "Upcoming Placement deadline" ,html)

