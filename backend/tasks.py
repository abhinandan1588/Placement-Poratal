def build_monthly_report_html(start , end):
    drives = PlacementDrive.query.filter(
        PlacementDrive.created_at >=start , PlacementDrive.created_at < end
    ).all()
    apps = Application.query.filter(
        Application.application_date >= start , Application.application_date < end
    ).all()
    selected = [a for a in apps if a.status == "selected"]

    rows = "".join(
        f"<tr><td>{d.job_title}</td><td>{d.company.company_name if d.company else '-'}</td>"
        f"<td>{d.status}</td><td>{len(d.applications)}</td></tr>"
        for d in drives
    )
    if not rows:
        rows = "<tr><td colspan='4' style='text-align:center'>No drives this month</td></tr>"
    return f"""
    <html><body style="font-family:Arial,sans-serif;color:#222">
      <h2 style="color:#2c3e50">Monthly Placement Activity Report</h2>
      <p>Period: <b>{start.date()}</b> to <b>{(end - timedelta(days=1)).date()}</b></p>
      <div style="display:flex;gap:16px;margin:16px 0">
        <div style="padding:12px;border:1px solid #ddd;border-radius:8px">
          <h3 style="margin:0">{len(drives)}</h3><div>Drives conducted</div></div>
        <div style="padding:12px;border:1px solid #ddd;border-radius:8px">
          <h3 style="margin:0">{len(apps)}</h3><div>Applications received</div></div>
        <div style="padding:12px;border:1px solid #ddd;border-radius:8px">
          <h3 style="margin:0">{len(selected)}</h3><div>Students selected</div></div>
      </div>
      <table border="1" cellpadding="8" cellspacing="0"
             style="border-collapse:collapse;width:100%">
        <thead style="background:#2c3e50;color:#fff">
          <tr><th>Job Title</th><th>Company</th><th>Status</th><th>Applicants</th></tr>
        </thead>
        <tbody>{rows}</tbody>
      </table>
      <p style="margin-top:16px;color:#777">Generated by Placement Portal Application.</p>
    </body></html>
    """
@celery.task(name="tasks.send_monthly_report")
def send_monthly_report():
    today = date.today()
    first_this_month = datetime(today.year , today.month , today.day)
    last_month_end = first_this_month
    prev = (first_this_month - timedelta(days=1))
    last_month_start = datetime(prev.year , prev.month ,1)

    html = build_monthly_report_html(last_month_start , last_month_end)
    admin = User.query.filter_by(role ="admin").first()
    _send_email(admin.email , "Monthly Placement Activity Report" , html)
    return "Monthly report sent to the Admin"
