SMTP_HOST = 'localhost'
SMTP_PORT = 1025
SENDER_EMAIL = "placemetcell@ppa.com"
SENDER_PASSWORD = ""

def _send_email(to_address, subject, body ,content_type="text", attachments=None):
    msg = MIMEMultipart()
    msg['To'] = to_address
    msg['Subject'] = subject
    msg['From'] = "placemetcell@ppa.com"
    
    if content_type == "html":
        msg.attach(MIMEText(body, 'html'))
    else:
        msg.attach(MIMEText(body, 'plain'))
    s = smtplib.SMTP(SMTP_HOST, SMTP_PORT)
    s.login(SENDER_EMAIL, SENDER_PASSWORD)
    s.send_message(msg)
    s.quit()
    return True 

