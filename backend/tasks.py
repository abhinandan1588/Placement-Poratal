@celery.task(name="tasks.export_applications_csv" , bind = True)
def export_applications_csv(self , student_id):
    student = StudentProfile.query.get(student_id)
    if not student:
        return {"status":"error" , "message":"Student not found"}
    filename = f"applications_student_{student_id}_{int(datetime.utcnow().timestamp())}.csv"
    filepath = os.path.join(Config.Export , filename)

    with open(filepath , "w" , newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(
            ["Student ID", "Company Name", "Drive Title", "Application Status", "Application Date", "Interview Date"]
        )
        for app in student.applications:
            drive = app.drive
            writer.writerow([
                student.id,
                drive.company.company_name if drive and drive.company else "",
                drive.job_title if drive else "",
                app.status,
                app.application_date.strftime("%Y-%m-%d %H:%M") if app.application_date else "",
                app.interview_datetime.strftime("%Y-%m-%d %H:%M") if app.interview_datetime else "",
            ])

    _send_email(
        student.user.email,
        "Your application export is ready",
        f"<p>Hi {student.name}, </p><p>Your placement application history"
        f"has been exported to <b>{filename}</b> and is already to download"
        f"from your dashboard</p>"

    )
    return {"status":"done", "filename":filename}